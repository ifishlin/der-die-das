import type { Grade, Operator, Question } from './types';

type Row = [left: number, op: '+' | '−' | '×', right: number, tag: string];

const OP: Record<Row[1], Operator> = { '+': 'add', '−': 'subtract', '×': 'multiply' };

function build(grade: Grade, prefix: string, rows: Row[]): Question[] {
  return rows.map(([left, op, right, tag], i) => ({
    id: `${prefix}-${String(i + 1).padStart(2, '0')}`,
    grade,
    operator: OP[op],
    left,
    right,
    tags: [tag],
  }));
}

