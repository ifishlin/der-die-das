export function presetFor(grade: Grade, kind: PresetKind): Question[] {
  if (kind === 'thousand') return grade === 2 ? GRADE2_THOUSAND : [];
  if (kind === 'multiply') return grade === 2 ? GRADE2_MULTIPLY : [];
  return grade === 1 ? GRADE1_PRESET : GRADE2_PRESET;
}
