"""Build one picture-book study page: data.js, Katja audio, tiny blurred page icons.
Usage: PYTHONPATH=<edge-tts dir> python3 tools/books/build.py <book-id>
Content is my own simple German + zh + grammar notes; no book text or pictures are copied."""
import asyncio, glob, importlib.util, json, os, re, shutil, subprocess, sys, tempfile, time, urllib.parse
from PIL import Image, ImageFilter
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
bid = sys.argv[1]
def load(name, path):
    sp = importlib.util.spec_from_file_location(name, path); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m); return m
meta = load('meta', f'{HERE}/{bid}/meta.py').META
spreads = load('content', f'{HERE}/{bid}/content.py').SPREADS
OUT = f'{REPO}/books/{bid}'
os.makedirs(OUT + '/audio', exist_ok=True); os.makedirs(OUT + '/icons', exist_ok=True)

# ---- IPA: plain-word values are dictionary keys (de.wiktionary), anything else is a literal IPA string
cache_f = f'{HERE}/ipa_cache.json'
cache = json.load(open(cache_f)) if os.path.exists(cache_f) else {}
def lookup(page):
    u = 'https://de.wiktionary.org/w/api.php?' + urllib.parse.urlencode({'action': 'parse', 'page': page, 'prop': 'wikitext', 'format': 'json'})
    for t in range(3):
        time.sleep(1.2)
        try:
            w = json.loads(subprocess.run(['curl', '-s', '-A', 'der-die-das/1.0 (ifishlin324@gmail.com)', u], capture_output=True).stdout)['parse']['wikitext']['*']
            m = re.search(r'\{\{Lautschrift\|([^}|]+)', w[w.index('{{Aussprache}}'):])
            if m: return m.group(1).replace('͡', '')
        except Exception: pass
    return ''
missing = []
def ipa_of(v):
    if re.fullmatch(r'[A-Za-zäöüß]+', v):
        if not cache.get(v): cache[v] = lookup(v); json.dump(cache, open(cache_f, 'w'), ensure_ascii=False, indent=1)
        if cache[v]: return cache[v]
        missing.append(v)
    return v

slug = lambda s: re.sub(r'[^a-z0-9]+', '_', s.lower().replace('ä', 'ae').replace('ö', 'oe').replace('ü', 'ue').replace('ß', 'ss')).strip('_')
jobs = {}
def aud(text, path): jobs[path] = text; return path
data = dict(id=bid, title=meta['title'], author=meta['author'], zh=meta['zh'], blurb=meta['blurb'], spreads=[])
for i, sp in enumerate(spreads, 1):
    n = f'{i:02d}'
    d = dict(n=i, zh=sp['zh'], icon=f'icons/p{n}.jpg')
    d['main'] = [dict(de=de, zh=zh, gram=g, audio=aud(de, f'audio/s{n}_m{j}.mp3')) for j, (de, zh, g) in enumerate(sp['main'])]
    d['side'] = [dict(de=de, zh=zh, gram=g, audio=aud(de, f'audio/s{n}_s{j}.mp3')) for j, (de, zh, g) in enumerate(sp['side'])]
    d['words'] = [dict(de=w[0], zh=w[1], ipa=ipa_of(w[2]), note=w[3], audio=aud(w[0], f'audio/w_{slug(w[0])}.mp3')) for w in sp['words']]
    data['spreads'].append(d)
if missing: print('IPA missing (shown as typed):', sorted(set(missing)))
open(f'{OUT}/data.js', 'w').write(f'// Generated by tools/books/build.py {bid}. Edit tools/books/{bid}/content.py, not this file.\nconst BOOK = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')

# ---- registry of all books
books = []
for m in sorted(glob.glob(f'{HERE}/*/meta.py')):
    mm = load('m', m).META
    if os.path.exists(f"{REPO}/books/{mm['id']}/data.js"):
        books.append(dict(id=mm['id'], title=mm['title'], author=mm['author'], zh=mm['zh'], blurb=mm['blurb']))
open(f'{REPO}/books/books.js', 'w').write('// Generated by tools/books/build.py. One entry per book folder.\nconst BOOKS = ' + json.dumps(books, ensure_ascii=False, indent=1) + ';\n')

# ---- blurred thumbnails of the real photos (whole photo, not cropped): small and blurred so no text or picture detail is readable
pd = meta.get('photos_dir')
if pd and os.path.isdir(pd):
    fs = sorted(glob.glob(pd + '/*.jp*g'), key=os.path.getmtime)
    for i, k in enumerate(meta['photo_order'], 1):
        im = Image.open(fs[k]).convert('RGB')
        im = im.rotate(90, expand=True) if im.width < im.height else im.rotate(180, expand=True)
        im = im.resize((120, 90), Image.LANCZOS).filter(ImageFilter.GaussianBlur(2.5))
        im.save(f'{OUT}/icons/p{i:02d}.jpg', quality=55)

# ---- audio (Katja); retries, never leave tiny/empty files
sys.path.insert(0, os.environ.get('PYTHONPATH', ''))
import edge_tts
async def one(path, text):
    if os.path.exists(f'{OUT}/{path}') and os.path.getsize(f'{OUT}/{path}') > 1000: return True
    for t in range(6):
        tmp = tempfile.mktemp(suffix='.mp3')
        try:
            await asyncio.wait_for(edge_tts.Communicate(text, 'de-DE-KatjaNeural', rate='-10%').save(tmp), 25)
            if os.path.getsize(tmp) > 1000: shutil.move(tmp, f'{OUT}/{path}'); return True
        except Exception: pass
        await asyncio.sleep(3 * (t + 1))
    return False
async def main():
    bad = [p for p, t in jobs.items() if not await one(p, t)]
    print('audio jobs', len(jobs), 'failed', bad)
asyncio.run(main())
