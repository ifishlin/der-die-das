"""Add a week of school-schedule days to schedule-data.js (data + Katja audio).
Usage: PYTHONPATH=<edge-tts dir> python3 tools/schedule/build.py week_2026_11_02
A week file defines DAYS_NEW (see week_2026_11_02.py). Re-running replaces days with the same date and keeps other days."""
import asyncio, importlib.util, json, os, re, shutil, subprocess, sys, tempfile, time, urllib.parse
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(HERE))
spec = importlib.util.spec_from_file_location('week', f'{HERE}/{sys.argv[1]}.py'); wk = importlib.util.module_from_spec(spec); spec.loader.exec_module(wk)
cache_f = f'{HERE}/ipa_cache.json'
cache = json.load(open(cache_f)) if os.path.exists(cache_f) else {}
def lookup(page):
    if page in cache: return cache[page]
    u = 'https://de.wiktionary.org/w/api.php?' + urllib.parse.urlencode({'action': 'parse', 'page': page, 'prop': 'wikitext', 'format': 'json'})
    r = ''
    for t in range(3):
        time.sleep(1.2)
        try:
            w = json.loads(subprocess.run(['curl', '-s', '-A', 'der-die-das/1.0 (ifishlin324@gmail.com)', u], capture_output=True).stdout)['parse']['wikitext']['*']
            m = re.search(r'\{\{Lautschrift\|([^}|]+)', w[w.index('{{Aussprache}}'):])
            if m: r = m.group(1).replace('͡', ''); break
        except Exception: pass
    cache[page] = r; json.dump(cache, open(cache_f, 'w'), ensure_ascii=False, indent=1); return r
KEEP = {'die Hausaufgaben', 'die Mathe'}
slug = lambda s: re.sub(r'[^a-z0-9]+', '_', s.lower().replace('ä', 'ae').replace('ö', 'oe').replace('ü', 'ue').replace('ß', 'ss')).strip('_')
jobs = {}
def aud(text, path): jobs[path] = text; return path
diffs = []
days = []
for D in wk.DAYS_NEW:
    pre = 'd' + D['date'][5:].replace('-', '')
    items = []
    for ii, it in enumerate(D['items']):
        o = dict(color=it['color'], title=it['title'], zh=it['zh'], original=it['original'], originalZh=it['originalZh'], originalGram=it['originalGram'])
        o['originalAudio'] = aud(it['original'], f'audio/sched/{pre}_{ii}_orig.mp3')
        o['titleAudio'] = aud(it['title'].replace('·', '.'), f'audio/sched/{pre}_{ii}_title.mp3')
        o['lines'] = [dict(de=d, zh=z, gram=g, audio=aud(d, f'audio/sched/{pre}_{ii}_{j}.mp3')) for j, (d, z, g) in enumerate(it['lines'])]
        o['words'] = []
        for de, zh, ipa, note, comp in it['words']:
            if not comp and de not in KEEP:
                base = re.sub(r'^(der|die|das|sich) ', '', de)
                got = lookup(base)
                if got and got != ipa: diffs.append((de, ipa, got))
                if got: ipa = got
            o['words'].append(dict(de=de, zh=zh, ipa=ipa, composed=comp, note=note, audio=aud(de, f'audio/sched/w_{slug(de)}.mp3')))
        items.append(o)
    days.append(dict(date=D['date'], label=D['label'], zh=D['zh'], items=items))
for d in diffs: print('IPA from wiktionary replaced:', d)
f = f'{REPO}/schedule-data.js'
s = open(f).read(); cur = json.loads(s[s.index('['):s.rindex(']') + 1])
new_dates = {d['date'] for d in days}
cur = [d for d in cur if d['date'] not in new_dates] + days
cur.sort(key=lambda d: d['date'])
open(f, 'w').write('// Daily lesson plans for schedule.html. Generated by tools/schedule/build.py (week files in tools/schedule/).\nconst SCHEDULE = ' + json.dumps(cur, ensure_ascii=False, indent=1) + ';\n')
sys.path.insert(0, os.environ.get('PYTHONPATH', ''))
import edge_tts
async def one(path, text):
    p = f'{REPO}/{path}'
    if os.path.exists(p) and os.path.getsize(p) > 1000: return True
    for t in range(6):
        tmp = tempfile.mktemp(suffix='.mp3')
        try:
            await asyncio.wait_for(edge_tts.Communicate(text, 'de-DE-KatjaNeural', rate='-10%').save(tmp), 25)
            if os.path.getsize(tmp) > 1000: shutil.move(tmp, p); return True
        except Exception: pass
        await asyncio.sleep(3 * (t + 1))
    return False
async def main():
    bad = [p for p, t in jobs.items() if not await one(p, t)]
    print('audio jobs', len(jobs), 'failed', bad)
asyncio.run(main())
